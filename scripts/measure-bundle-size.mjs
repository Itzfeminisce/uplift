import { gzipSync } from "node:zlib";
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const dist = path.join(root, "packages", "uplift", "dist");
const docsOut = path.join(root, "docs", "bundle-size.json");
const siteOut = path.join(root, "site", "bundle-size.json");
const mdOut = path.join(root, "docs", "BUNDLE_SIZE.md");

const files = (await readdir(dist, { recursive: true }))
  .filter((file) => file.endsWith(".js") && !file.endsWith(".d.ts"))
  .sort();

if (files.length === 0) {
  throw new Error("No built JavaScript files found. Run pnpm build before measuring bundle size.");
}

const entries = await Promise.all(files.map(async (file) => {
  const absolute = path.join(dist, file);
  const source = await readFile(absolute);
  return {
    file: file.replaceAll("\\", "/"),
    bytes: source.byteLength,
    gzipBytes: gzipSync(source).byteLength
  };
}));

const payload = {
  generatedAt: new Date().toISOString(),
  package: "uplift",
  version: "0.0.0",
  entries,
  totalBytes: entries.reduce((sum, entry) => sum + entry.bytes, 0),
  totalGzipBytes: entries.reduce((sum, entry) => sum + entry.gzipBytes, 0)
};

await mkdir(path.dirname(docsOut), { recursive: true });
await mkdir(path.dirname(siteOut), { recursive: true });
await writeFile(docsOut, `${JSON.stringify(payload, null, 2)}\n`);
await writeFile(siteOut, `${JSON.stringify(payload, null, 2)}\n`);
await writeFile(mdOut, [
  "# Bundle Size",
  "",
  "Generated by `pnpm bundle:size` after `pnpm build`.",
  "",
  "| Entry | Bytes | Gzip |",
  "| --- | ---: | ---: |",
  ...entries.map((entry) => `| \`${entry.file}\` | ${entry.bytes} | ${entry.gzipBytes} |`),
  "",
  `Total gzip: ${payload.totalGzipBytes} bytes`,
  ""
].join("\n"));

console.log(`Measured ${entries.length} built files. Total gzip: ${payload.totalGzipBytes} bytes.`);
